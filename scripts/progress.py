"""Rebuild the progress section of README.md from the solution files.

    python scripts/progress.py          # rewrite the section
    python scripts/progress.py --check  # exit 1 if README.md is out of date (no changes made)

Everything comes from the header lines at the top of each file in solutions/ and from
which pattern files exist in patterns/.
"""

import sys
from collections import Counter
from datetime import date, timedelta

from sqlpractice import README, SOURCES, TOPICS, load_solutions, needs_redo, pattern_status

START = "<!-- progress:start -->"
END = "<!-- progress:end -->"


def md(text):
    return str(text).replace("|", "\\|")


def build(today=None):
    today = today or date.today()
    rows = load_solutions()
    patterns = pattern_status()
    done_patterns = sum(1 for _, _, ok in patterns if ok)
    out = ["## Progress", "", "_Generated by `scripts/progress.py` from the solution files._", ""]

    if not rows:
        out += ["No solutions saved yet.", ""]
    else:
        last7 = [r for r in rows if r["date"] and 0 <= (today - r["date"]).days <= 6]
        no_hint = [r for r in rows if r["hints"] in ("none", "")]
        redo = [r for r in rows if needs_redo(r)]
        share = round(100 * len(no_hint) / len(rows))
        out.append(
            f"**{len(rows)}** problems solved · **{len(last7)}** in the last 7 days · "
            f"**{share}%** without opening the solution · **{done_patterns}/{len(patterns)}** patterns written"
            + (f" · **{len(redo)}** waiting for a redo" if redo else "")
        )
        out.append("")

        by_topic = Counter(r["topic"] or "untagged" for r in rows)
        by_source = Counter(r["source_label"] for r in rows)
        by_diff = Counter((r["difficulty"] or "-").title() for r in rows)
        topics = [t for t in TOPICS if by_topic.get(t)] + sorted(t for t in by_topic if t not in TOPICS)
        out += ["| Topic | Solved |", "|---|---:|"]
        out += [f"| {md(t)} | {by_topic[t]} |" for t in topics]
        out.append("")
        sources = [SOURCES[k][0] for k in SOURCES if by_source.get(SOURCES[k][0])]
        sources += sorted(s for s in by_source if s not in sources)
        line = "By source: " + " · ".join(f"{s} {by_source[s]}" for s in sources)
        diffs = [d for d in ("Easy", "Medium", "Hard") if by_diff.get(d)]
        if diffs:
            line += "  \nBy difficulty: " + " · ".join(f"{d} {by_diff[d]}" for d in diffs)
        out += [line, ""]

        # last 8 weeks, Monday-start
        monday = today - timedelta(days=today.weekday())
        weeks = []
        for i in range(7, -1, -1):
            start = monday - timedelta(weeks=i)
            n = sum(1 for r in rows if r["date"] and start <= r["date"] < start + timedelta(days=7))
            weeks.append((start, n))
        if any(n for _, n in weeks):
            out += ["| Week of | " + " | ".join(f"{s:%b} {s.day}" for s, _ in weeks) + " |",
                    "|---|" + "---:|" * len(weeks),
                    "| Solved | " + " | ".join(str(n) for _, n in weeks) + " |", ""]

        out += ["### Latest", "", "| Date | Problem | Topic | Pattern | Solution opened? |", "|---|---|---|---|---|"]
        for r in rows[:10]:
            d = r["date"].isoformat() if r["date"] else "-"
            opened = "yes, redone" if ("solution" in r["hints"] and not needs_redo(r)) else ("yes" if "solution" in r["hints"] else "no")
            out.append(f"| {d} | [{md(r['source'])} · {md(r['title'])}]({r['rel']}) | {md(r['topic'] or '-')} | {md(r['pattern'] or '-')} | {opened} |")
        out.append("")

    out += ["### Pattern library", ""]
    for stem, label, ok in patterns:
        out.append(f"- [{'x' if ok else ' '}] " + (f"[{label}](patterns/{stem}.sql)" if ok else label))
    out.append("")
    return "\n".join(out)


def main():
    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        sys.exit(f"README.md needs the {START} and {END} markers.")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    new = f"{head}{START}\n{build()}{END}{tail}"
    if "--check" in sys.argv:
        if new != text:
            sys.exit("README.md progress is out of date: run python scripts/progress.py")
        print("README.md progress is up to date.")
        return
    if new != text:
        with open(README, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(new)
        print("Updated the progress section in README.md")
    else:
        print("README.md progress already up to date.")


if __name__ == "__main__":
    main()
